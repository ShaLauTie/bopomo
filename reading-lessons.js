// 每一行拆成字：[{ch, zy}]，標點 zy 是空字串
function readingLineChars(line) {
  const [text, zhuyin] = line;
  const zys = zhuyin.trim().split(/\s+/);
  let k = 0;
  return [...text].map(ch => {
    if (/[一-鿿]/.test(ch)) return { ch, zy: zys[k++] || "" };
    return { ch, zy: "" };
  });
}

// 姨姨的語音：單字「念:沙ㄕㄚ」，整句「念句:沙灘上堆城堡，」
function readingCharKey(ch, zy) { return `念:${ch}${zy}`; }
function readingLineKey(text) { return `念句:${text}`; }
function readingTtsKeys() {
  const keys = new Set();
  READING_LESSONS.forEach(l => l.lines.forEach(line => {
    keys.add(readingLineKey(line[0]));
    readingLineChars(line).forEach(c => { if (c.zy) keys.add(readingCharKey(c.ch, c.zy)); });
  }));
  return [...keys];
}
