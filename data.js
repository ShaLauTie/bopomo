const BPMF_INITIALS = "ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙ";
const BPMF_TONE_RE = /[ˊˇˋ˙]/g;

// 拆一個音節：「ㄒㄧㄤˋ」→ { initial:"ㄒ", rime:"ㄧㄤ", tone:"ˋ" }
function parseSyllable(z) {
  const toneMatch = z.match(/[ˊˇˋ˙]/);
  const tone = toneMatch ? toneMatch[0] : "";
  const body = z.replace(BPMF_TONE_RE, "");
  const initial = BPMF_INITIALS.includes(body[0]) ? body[0] : "";
  return { initial, rime: body.slice(initial.length), tone, body };
}

